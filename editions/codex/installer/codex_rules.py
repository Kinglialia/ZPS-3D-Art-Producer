#!/usr/bin/env python3
"""Write a Codex rules file that lets headless Blender run the Producer's installed scripts outside the sandbox.

Why: on macOS, Blender crashes inside the Codex sandbox (the sandbox blocks the Metal GPU check). Copied from the kit's
installer/codex_rules.py (v0.10.4). The rule allows only these literal commands:
  <Blender> -b --python <installed Producer script>.py -- ...
  <Blender> -b --python-exit-code 1 --python <installed Producer script>.py -- ...
  <Producer venv python> <scripts/assemble.py> --blender <Blender> -- ...   (it starts Blender itself)
  <scripts/run_tool.py> --blender <Blender> ...                             (the RUN line of a brief; it starts Blender)
A Codex rule matches only the start of a command, so each rule ends where the program stops reading options: Blender
gives the arguments after `--` to the script, assemble.py reads only positionals after `--`, and in the Codex edition
run_tool.py refuses scripts/ and the NETWORK_SCRIPTS and AGENT_CODE tools itself.
Its --blender must equal the preflight Blender, but a worker can edit that file, so the rule pins --blender too.
run_tool.py refuses a flag given twice, so the pinned --blender is the one that runs. Scripts that call paid or network services (NETWORK_SCRIPTS) never match.
gen_image_codex.py stays in that list: this edition runs only its --direct check, which writes under production*/ and
runs inside the sandbox with no rule (D46). Scripts that run code the agent
wrote (AGENT_CODE: graph.py loads <work>/parts_lib.py, custom_mesh.py runs custom_parts.py) never match either. Any other command still runs in the sandbox
or asks the user. The skills folder is read-only inside the sandbox, so an agent cannot change the allowed scripts.
A rule matches only a bare first word, never a quoted one (measured 2026-11-13). When the Producer folder needs quotes
(a space in the project path), the rules name it through $CODEX_HOME/zps-3dp/<12 hex of sha1 of the folder>, a link
that --write makes or repairs and that the briefs use too (core.state.rule_dir). The direct Blender rules keep the real
script paths, because a later word may be quoted; when Blender itself needs quotes, those two rules are left out.

Usage (run outside Codex, from the project, after install.py):
  python3 installer/codex_rules.py            # preview the file and self-test it, write nothing
  python3 installer/codex_rules.py --write    # write $CODEX_HOME/rules/zps-3dp-producer.rules
Options: --skills-root (default .agents/skills), --blender, --rules-dir (default $CODEX_HOME/rules or ~/.codex/rules).
Run it again after each upgrade: the file lists the installed scripts. Restart Codex after writing."""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import sys
import tempfile

MARK = "# Generated by ZPS-3DP Producer installer/codex_rules.py. Regenerate after each upgrade."
FILE = "zps-3dp-producer.rules"
MAC_BLENDER = "/Applications/Blender.app/Contents/MacOS/Blender"
PRODUCER = "zps-3dp-producer-codex"
NETWORK_SCRIPTS = ("gen_api.py", "generate_image.py", "meshy_call.py", "gen_image_codex.py")
AGENT_CODE = ("self_build/assembly.py", "self_build/param_fit.py", "tools/custom_mesh.py")
SPAWNERS = ("scripts/assemble.py",)


def find_blender(given):
    """Keep a link as found: the RUN line prints the preflight Blender unresolved, and the rule must pin that string."""
    for p in (given, os.environ.get("BLENDER"), MAC_BLENDER, shutil.which("blender")):
        if p and os.path.isfile(p) and os.access(p, os.X_OK):
            return p
    return None


def skill_dirs(root: Path) -> list[Path]:
    return sorted(p for p in root.glob("zps-3dp-*-codex") if p.is_dir())


def scripts(root: Path, network: bool = False) -> list[str]:
    out = []
    for base in skill_dirs(root):
        for p in sorted(base.rglob("*.py")):
            if ".deps" not in p.parts and "__pycache__" not in p.parts and (p.name in NETWORK_SCRIPTS) == network \
                    and not p.as_posix().endswith(AGENT_CODE):
                out.append(str(p))
    return out


def agent_code(root: Path) -> list[str]:
    return [str(p) for base in skill_dirs(root) for p in sorted(base.rglob("*.py")) if p.as_posix().endswith(AGENT_CODE)]


def q(s) -> str:
    return json.dumps(s)


def rule(pattern: list, why: str) -> str:
    head = ", ".join(q(x) if isinstance(x, str) else "[\n        " + ",\n        ".join(map(q, x)) + ",\n    ]"
                     for x in pattern)
    return f'prefix_rule(\n    pattern = [{head}],\n    decision = "allow",\n    justification = {q(why)},\n)\n'


def needs_quotes(p) -> bool:
    return shlex.quote(str(p)) != str(p)


def link_of(prod: Path) -> Path:
    """Where the briefs name a Producer folder whose path needs quotes. Same formula as core.state.codex_link, which this
    script cannot import: it runs outside the skill."""
    return (Path(os.environ.get("CODEX_HOME") or "~/.codex").expanduser() / "zps-3dp"
            / hashlib.sha1(str(prod).encode()).hexdigest()[:12])


def make_link(link: Path, prod: Path) -> bool:
    """Create or repair the link. Never replace a real file or folder."""
    if link.is_symlink():
        if link.resolve() == prod:
            return True
        link.unlink()
    elif link.exists():
        return False
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(prod, target_is_directory=True)
    return True


def render(blender: str, allowed: list[str], venv_py: Path | None, prod: Path) -> str:
    """prod is the Producer folder as the briefs name it: the link when the real path needs quotes."""
    why = ("ZPS-3DP Producer: Blender crashes inside the Codex sandbox on macOS (Metal GPU check). "
           "Allow headless Blender to run only the installed Producer scripts.")
    out = [MARK, ""]
    for prefix in (["-b", "--python"], ["-b", "--python-exit-code", "1", "--python"]) if not needs_quotes(blender) else ():
        out.append(rule([blender, *prefix, allowed, "--"], why))
    out.append(rule([str(prod / "scripts/run_tool.py"), "--blender", blender],
                    "ZPS-3DP Producer: run_tool.py runs a worker's tool and starts Blender itself, so it must run outside the sandbox."))
    if venv_py:
        out.append(rule([str(venv_py), [str(prod / s) for s in SPAWNERS], "--blender", blender, "--"],
                        "ZPS-3DP Producer: assemble.py starts Blender itself, so it must run outside the sandbox."))
    return "\n".join(out)


def self_test(path: Path, blender: str, allowed: list[str], venv_py: Path | None, prod: Path, root: Path) -> str:
    codex = shutil.which("codex")
    if not codex:
        return "codex CLI not found: rule not tested"
    cases = [([blender, "-b", "--python", allowed[0], "--", "x"], "allow"),
             ([blender, "-b", "--python-exit-code", "1", "--python", allowed[-1], "--"], "allow"),
             ([blender, "-b", "--python", allowed[0]], None),
             ([blender, "-b", "--python", allowed[0], "--python-expr", "print(1)"], None),
             ([blender, "-b", "--python", allowed[0], "--python", "/tmp/evil.py", "--"], None),
             ([blender, "-b", "--python-exit-code", "1", "--python", allowed[-1], "--python-expr", "print(1)"], None),
             ([blender, "-b", "--python-expr", "print(1)"], None),
             ([blender, "-b", "--python", "/tmp/other.py", "--"], None)] if not needs_quotes(blender) else []
    cases += [([blender, "-b", "--python", n, "--", "generate"], None) for n in scripts(root, network=True)]
    cases += [([blender, "-b", "--python", n, "--", "--work", "w"], None) for n in agent_code(root)]
    cases.append((["codex", "exec", "-s", "workspace-write", "--skip-git-repo-check", "-"], None))
    run_tool = str(prod / "scripts/run_tool.py")
    cases += [([run_tool, "--blender", blender, "--agent", "zps-3dp-step-model-codex", "--version-dir", "v", "bl", "join_mesh.py"],
               "allow"),
              ([run_tool, "--blender", "/tmp/evil.sh", "--agent", "zps-3dp-step-model-codex"], None),
              ([run_tool, "--agent", "zps-3dp-step-model-codex", "--version-dir", "v", "x.py"], None)]
    if venv_py:
        py, spawner = str(venv_py), str(prod / SPAWNERS[0])
        cases += [([py, spawner, "--blender", blender, "--", "house-a", "1", "abc123"], "allow"),
                  ([py, spawner, "house-a", "--version", "1", "--blender", "/tmp/evil.sh"], None),
                  ([py, spawner, "--blender", "/tmp/evil.sh", "--", "house-a", "1", "abc123"], None),
                  ([py, str(prod / "scripts/producer.py"), "preflight"], None),
                  ([py, str(prod / "scripts/producer.py"), "brief", "house-a"], None),
                  ([py, str(prod / "scripts/meshy_call.py"), "texture"], None),
                  ([py, str(prod / "scripts/gen_image_codex.py"), "--model", "m"], None),
                  ([py, "-c", "print(1)"], None)]
    bad = []
    for cmd, want in cases:
        r = subprocess.run([codex, "execpolicy", "check", "--rules", str(path), "--", *cmd], capture_output=True, text=True)
        got = json.loads(r.stdout or "{}").get("decision")
        if got != want:
            bad.append(f"{' '.join(cmd)} -> {got}, expected {want}")
    return "rule test passed" if not bad else "RULE TEST FAILED: " + "; ".join(bad)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skills-root", type=Path, default=Path(".agents/skills"))
    ap.add_argument("--blender")
    ap.add_argument("--rules-dir", type=Path, default=Path(os.environ.get("CODEX_HOME") or "~/.codex") / "rules")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    root = a.skills_root.expanduser().resolve()
    blender = find_blender(a.blender)
    if not blender:
        print("Blender not found. Install it or pass --blender /path/to/Blender.")
        return 2
    allowed = scripts(root)
    if not allowed:
        print(f"No installed Producer scripts in {root}. Run install.py first.")
        return 2
    prod = root / PRODUCER
    link = link_of(prod) if needs_quotes(prod) else None
    if link and needs_quotes(link):
        print(f"{link} needs quotes too: set CODEX_HOME to a folder whose path has no space or quote. Nothing written.")
        return 2
    base = link or prod
    venv_py = prod / "scripts/.deps/venv/bin/python"
    if not venv_py.exists():
        print(f"Note: {venv_py} does not exist yet. Run setup_deps.sh, then run this script again.")
        venv_py = None
    if needs_quotes(blender):
        print(f"Note: {blender} needs quotes, so no direct Blender rule is written; run_tool.py and assemble.py still run it.")
    rule_py = base / "scripts/.deps/venv/bin/python" if venv_py else None
    text = render(blender, allowed, rule_py, base)
    target = a.rules_dir.expanduser() / FILE
    fd, name = tempfile.mkstemp(prefix=f"{FILE}.", suffix=".preview")
    os.close(fd)
    tmp = Path(name)
    tmp.write_text(text, encoding="utf-8")
    result = self_test(tmp, blender, allowed, rule_py, base, root)
    print(f"Blender: {blender}\nProducer scripts: {len(allowed)}\nvenv rules: {'yes' if venv_py else 'no'}\n{result}")
    if "FAILED" in result:
        return 1
    if link:
        print(f"Link: {link} -> {prod}" + ("" if a.write else " (made by --write)"))
    if not a.write:
        print(f"Preview only: {tmp}\nRun with --write to install it as {target}.")
        return 0
    if target.exists() and MARK not in target.read_text(encoding="utf-8"):
        print(f"{target} exists and was not written by this script. Nothing written.")
        return 1
    if link and not make_link(link, prod):
        print(f"{link} exists and is not a link. Move it away, then run this script again. Nothing written.")
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"Wrote {target}. Restart Codex to load it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
